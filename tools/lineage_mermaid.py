"""Write the dbt lineage as a Mermaid graph in docs/lineage.md, from dbt's manifest.

GitHub draws Mermaid itself, so the picture stays sharp and is rebuilt from the project
instead of being a screenshot that goes stale. One node per model, grouped by its folder
(staging, intermediate, marts, then any other), each labelled with the number of data tests
attached to it; one node per source table; the seeds (market rules, holidays) as one node,
since nearly every layer reads them. Only names and counts: no data, no warehouse, no
project id. The counts in the page header are computed here, so they cannot go stale.

The manifest comes from any dbt command on the CI profile, for example
`dbt parse --profiles-dir ci --target ci` in dbt/ (no warehouse, no credentials).

Exit codes: 0 = the page is current, or written with `--apply` · 1 = `--check` found the
page out of date, or a self-test failed · 2 = cannot run (no manifest, unreadable, an
unknown argument).

Usage:
    python tools/lineage_mermaid.py            # dry run: says whether the page would change
    python tools/lineage_mermaid.py --apply    # writes docs/lineage.md
    python tools/lineage_mermaid.py --check    # exit 1 if the page is out of date (CI)
    python tools/lineage_mermaid.py --self-test
"""

from __future__ import annotations

import argparse
import dataclasses
import json
import subprocess
import sys
import tempfile
from collections import Counter
from pathlib import Path

from vnmarket.common.config import REPO_ROOT, utf8_stdio

MANIFEST = REPO_ROOT / "dbt" / "target" / "manifest.json"
OUT = REPO_ROOT / "docs" / "lineage.md"
LAYERS = ("staging", "intermediate", "marts")  # drawn in this order, any other folder after
ROOT_LAYER = "models"  # a model directly under models/
SEEDS_NODE = "seeds"
CHECK_TIMEOUT_SECONDS = 60  # the self-test's own calls of this script


@dataclasses.dataclass(frozen=True)
class Lineage:
    layers: dict[str, list[str]]  # folder -> model names
    tests_per_model: Counter  # model name -> data tests attached to it
    distinct_tests: int  # data tests with at least one model parent, each counted once
    parents: dict[str, list[str]]  # model name -> parent node ids
    sources: list[str]  # source node ids, "<source>__<table>"
    seeds: int


def lineage(manifest: dict) -> Lineage:
    nodes = manifest["nodes"]
    models = {k: v for k, v in nodes.items() if v["resource_type"] == "model"}
    tests_per_model: Counter = Counter()
    distinct = 0
    for v in nodes.values():
        if v["resource_type"] != "test":
            continue
        model_parents = {p for p in v["depends_on"]["nodes"] if p in models}
        distinct += bool(model_parents)
        for p in model_parents:
            tests_per_model[models[p]["name"]] += 1
    layers: dict[str, list[str]] = {}
    for v in models.values():
        layer = v["fqn"][1] if len(v["fqn"]) > 2 else ROOT_LAYER
        layers.setdefault(layer, []).append(v["name"])
    parents: dict[str, list[str]] = {}
    sources = set()
    for v in models.values():
        found = set()
        for p in v["depends_on"]["nodes"]:
            if p in models:
                found.add(models[p]["name"])
            elif p.startswith("seed."):
                found.add(SEEDS_NODE)
            elif p.startswith("source."):
                s = manifest["sources"][p]
                node = f"{s['source_name']}__{s['name']}"
                sources.add(node)
                found.add(node)
        parents[v["name"]] = sorted(found)
    return Lineage(
        layers={k: sorted(v) for k, v in layers.items()},
        tests_per_model=tests_per_model,
        distinct_tests=distinct,
        parents=parents,
        sources=sorted(sources),
        seeds=sum(1 for v in nodes.values() if v["resource_type"] == "seed"),
    )


def render(manifest: dict) -> str:
    g = lineage(manifest)
    order = [x for x in LAYERS if x in g.layers] + sorted(set(g.layers) - set(LAYERS))
    n_models = sum(len(v) for v in g.layers.values())
    lines = [
        "# dbt lineage",
        "",
        "Generated by `tools/lineage_mermaid.py --apply` from dbt's manifest; do not edit by hand.",
        f"{n_models} models, {len(g.sources)} source tables, {g.seeds} seeds; "
        f"{g.distinct_tests} data tests read at least one model. The number in each box is the "
        "data tests on that model (a test that reads two models counts in both).",
        "",
        "```mermaid",
        "flowchart LR",
        "  subgraph raw[sources - append-only]",
        *(f"    {s}[{s.replace('__', '.')}]" for s in g.sources),
        "  end",
        f"  {SEEDS_NODE}[({g.seeds} seeds: tick size, price band, holidays, ...)]",
    ]
    for layer in order:
        lines.append(f"  subgraph {layer}")
        for name in g.layers[layer]:
            n = g.tests_per_model[name]
            label = f"{name} · {n}" if n else name
            lines.append(f'    {name}["{label}"]')
        lines.append("  end")
    for child in sorted(g.parents):
        for parent in g.parents[child]:
            lines.append(f"  {parent} --> {child}")
    lines += ["```", ""]
    return "\n".join(lines)


def sample_manifest() -> dict:
    """Two models in two layers, a source, a seed; tests on one model, on two models, and on
    a seed only."""

    def model(name: str, fqn: list[str], deps: list[str]) -> dict:
        return {"resource_type": "model", "name": name, "fqn": fqn, "depends_on": {"nodes": deps}}

    def test(deps: list[str]) -> dict:
        return {"resource_type": "test", "depends_on": {"nodes": deps}}

    return {
        "nodes": {
            "model.p.stg_a": model("stg_a", ["p", "staging", "stg_a"], ["source.p.raw.a"]),
            "model.p.fct_b": model(
                "fct_b", ["p", "marts", "d", "fct_b"], ["model.p.stg_a", "seed.p.tick"]
            ),
            "seed.p.tick": {"resource_type": "seed", "depends_on": {"nodes": []}},
            "test.p.t1": test(["model.p.fct_b"]),
            "test.p.t2": test(["model.p.fct_b"]),
            "test.p.both": test(["model.p.stg_a", "model.p.fct_b"]),
            "test.p.seed_only": test(["seed.p.tick"]),
        },
        "sources": {"source.p.raw.a": {"source_name": "raw", "name": "a"}},
    }


def self_test() -> int:
    manifest = sample_manifest()
    g = lineage(manifest)
    page = render(manifest)
    # planted fault: a test moved from fct_b to stg_a must change the page, so --check fails
    planted = json.loads(json.dumps(manifest))
    planted["nodes"]["test.p.t1"]["depends_on"]["nodes"] = ["model.p.stg_a"]
    extra = json.loads(json.dumps(manifest))
    extra["nodes"]["model.p.x"] = {
        "resource_type": "model",
        "name": "x",
        "fqn": ["p", "other_folder", "x"],
        "depends_on": {"nodes": []},
    }
    script = Path(__file__).resolve()

    def call(*args: str) -> int:
        return subprocess.run(  # noqa: S603 - this script, fixed arguments
            [sys.executable, str(script), *args],
            capture_output=True,
            timeout=CHECK_TIMEOUT_SECONDS,
            check=False,
        ).returncode

    with tempfile.TemporaryDirectory() as tmp:
        mf, out = Path(tmp) / "manifest.json", Path(tmp) / "lineage.md"
        mf.write_text(json.dumps(manifest), "utf-8")
        dry = call("--manifest", str(mf), "--out", str(out))
        dry_wrote = out.exists()
        applied = call("--manifest", str(mf), "--out", str(out), "--apply")
        current = call("--manifest", str(mf), "--out", str(out), "--check")
        mf.write_text(json.dumps(planted), "utf-8")
        stale = call("--manifest", str(mf), "--out", str(out), "--check")
        bogus = call("--bogus")
    checks = {
        "layers come from the folder, a nested mart included": g.layers
        == {"staging": ["stg_a"], "marts": ["fct_b"]},
        "tests per model: a two-model test counts in both, a seed-only test in none": (
            g.tests_per_model == Counter({"fct_b": 3, "stg_a": 1})
        ),
        "distinct tests: a two-model test counted once": g.distinct_tests == 3,
        "parents: the source, the model and the seeds node": g.parents
        == {"stg_a": ["raw__a"], "fct_b": [SEEDS_NODE, "stg_a"]},
        "sources listed from the manifest": g.sources == ["raw__a"],
        "the page labels each box with its count": 'fct_b["fct_b · 3"]' in page,
        "the page draws the source edge": "raw__a --> stg_a" in page,
        "the page draws the seeds edge": "seeds --> fct_b" in page,
        "the header states the distinct count": "3 data tests read at least one model" in page,
        "a fourth folder gets its own box": "subgraph other_folder" in render(extra),
        "deterministic": render(manifest) == page,
        "planted: a moved test changes the page": render(planted) != page,
        "the default is a dry run: exit 0": dry == 0,
        "the default is a dry run: nothing written": not dry_wrote,
        "--apply writes": applied == 0,
        "--check passes on the page just written": current == 0,
        "planted: --check exits 1 on a stale page": stale == 1,
        "an unknown argument is refused with exit 2": bogus == 2,
    }
    for name, ok in checks.items():
        print(f"{'✅' if ok else '🔴'} {name}")
    return 0 if all(checks.values()) else 1


def main() -> int:
    utf8_stdio()
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--manifest", type=Path, default=MANIFEST)
    parser.add_argument("--out", type=Path, default=OUT)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--apply", action="store_true", help="write the page")
    mode.add_argument("--check", action="store_true", help="exit 1 if the page is out of date")
    mode.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        return self_test()
    try:
        page = render(json.loads(args.manifest.read_text("utf-8")))
    except (OSError, ValueError, KeyError) as exc:
        print(f"🔴 cannot read the manifest {args.manifest}: {type(exc).__name__}: {exc}")
        return 2
    if args.apply:
        args.out.write_text(page, "utf-8", newline="\n")
        print(f"✅ written {args.out}")
        return 0
    current = args.out.read_text("utf-8") if args.out.exists() else None
    if current == page:
        print(f"✅ {args.out.name} matches the models")
        return 0
    if args.check:
        print(f"🔴 {args.out.name} is out of date: run python tools/lineage_mermaid.py --apply")
        return 1
    print(f"⚪ dry run: {args.out.name} would change; --apply writes it")
    return 0


if __name__ == "__main__":
    sys.exit(main())
