"""Write the dbt lineage as a Mermaid graph in docs/lineage.md, from dbt's manifest.

GitHub draws Mermaid itself, so the picture stays sharp and is rebuilt from the project
instead of being a screenshot that goes stale. One node per model, grouped by layer
(staging, intermediate, marts), each labelled with the number of data tests attached to
it; one node per source table; the seeds (market rules, holidays) as one node, since
nearly every layer reads them. Only names and counts: no data, no warehouse, no project id.

The manifest comes from any dbt command on the CI profile, for example
`dbt parse --profiles-dir ci --target ci` in dbt/ (no warehouse, no credentials).

Exit codes: 0 = written, or `--check` found the page current · 1 = `--check` found the
page out of date, or a self-test failed · 2 = cannot run (no manifest, unreadable).

Usage:
    python tools/lineage_mermaid.py [--manifest PATH] [--out PATH]
    python tools/lineage_mermaid.py --check
    python tools/lineage_mermaid.py --self-test
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

from vnmarket.common.config import REPO_ROOT, utf8_stdio

MANIFEST = REPO_ROOT / "dbt" / "target" / "manifest.json"
OUT = REPO_ROOT / "docs" / "lineage.md"
LAYERS = ("staging", "intermediate", "marts")
SEEDS_NODE = "seeds"


def graph(manifest: dict) -> tuple[dict[str, list[str]], Counter, dict[str, str], int]:
    """Models by layer, data tests per model, edges (child -> parents as node ids) and the
    number of seeds."""
    nodes = manifest["nodes"]
    models = {k: v for k, v in nodes.items() if v["resource_type"] == "model"}
    tests: Counter = Counter()
    for v in nodes.values():
        if v["resource_type"] == "test":
            for parent in v["depends_on"]["nodes"]:
                if parent in models:
                    tests[models[parent]["name"]] += 1
    by_layer: dict[str, list[str]] = {layer: [] for layer in LAYERS}
    for v in models.values():
        layer = v["fqn"][1] if len(v["fqn"]) > 2 else "marts"
        by_layer.setdefault(layer, []).append(v["name"])
    edges: dict[str, list[str]] = {}
    for v in models.values():
        parents = set()
        for p in v["depends_on"]["nodes"]:
            if p in models:
                parents.add(models[p]["name"])
            elif p.startswith("seed."):
                parents.add(SEEDS_NODE)
            elif p.startswith("source."):
                s = manifest["sources"][p]
                parents.add(f"{s['source_name']}__{s['name']}")
        edges[v["name"]] = sorted(parents)
    seeds = sum(1 for v in nodes.values() if v["resource_type"] == "seed")
    return {k: sorted(v) for k, v in by_layer.items()}, tests, edges, seeds


def render(manifest: dict) -> str:
    by_layer, tests, edges, seeds = graph(manifest)
    sources = sorted({p for ps in edges.values() for p in ps if "__" in p and p not in edges})
    n_models = sum(len(v) for v in by_layer.values())
    n_tests = sum(tests.values())
    lines = [
        "# dbt lineage",
        "",
        "Generated by `tools/lineage_mermaid.py` from dbt's manifest; do not edit by hand.",
        f"{n_models} models, {len(sources)} source tables, {seeds} seeds, "
        f"{n_tests} data tests attached to models (the number in each box).",
        "",
        "```mermaid",
        "flowchart LR",
        "  subgraph raw[sources - append-only]",
        *(f"    {s}[{s.replace('__', '.')}]" for s in sources),
        "  end",
        f"  {SEEDS_NODE}[({seeds} seeds: tick size, price band, holidays, ...)]",
    ]
    for layer in LAYERS:
        if not by_layer.get(layer):
            continue
        lines.append(f"  subgraph {layer}")
        for name in by_layer[layer]:
            label = f"{name} · {tests[name]}" if tests[name] else name
            lines.append(f'    {name}["{label}"]')
        lines.append("  end")
    for child in sorted(edges):
        for parent in edges[child]:
            lines.append(f"  {parent} --> {child}")
    lines += ["```", ""]
    return "\n".join(lines)


def self_test() -> int:
    manifest = {
        "nodes": {
            "model.p.stg_a": {
                "resource_type": "model",
                "name": "stg_a",
                "fqn": ["p", "staging", "stg_a"],
                "depends_on": {"nodes": ["source.p.raw.a"]},
            },
            "model.p.fct_b": {
                "resource_type": "model",
                "name": "fct_b",
                "fqn": ["p", "marts", "d", "fct_b"],
                "depends_on": {"nodes": ["model.p.stg_a", "seed.p.tick"]},
            },
            "seed.p.tick": {
                "resource_type": "seed",
                "name": "tick",
                "fqn": ["p", "tick"],
                "depends_on": {"nodes": []},
            },
            "test.p.t1": {"resource_type": "test", "depends_on": {"nodes": ["model.p.fct_b"]}},
            "test.p.t2": {"resource_type": "test", "depends_on": {"nodes": ["model.p.fct_b"]}},
            "test.p.t3": {"resource_type": "test", "depends_on": {"nodes": ["seed.p.tick"]}},
        },
        "sources": {"source.p.raw.a": {"source_name": "raw", "name": "a"}},
    }
    page = render(manifest)
    by_layer, tests, edges, seeds = graph(manifest)
    # a planted fault: a test counted on a seed would show up as a test on a model
    planted = json.loads(json.dumps(manifest))
    planted["nodes"]["test.p.t3"]["depends_on"]["nodes"] = ["model.p.stg_a"]
    checks = {
        "layers from the fqn, a nested mart included": by_layer["staging"] == ["stg_a"]
        and by_layer["marts"] == ["fct_b"],
        "tests counted per model, a seed's test not counted": tests == Counter({"fct_b": 2}),
        "edges: source, model and the seeds node": edges
        == {"stg_a": ["raw__a"], "fct_b": [SEEDS_NODE, "stg_a"]},
        "the page labels the count and draws every edge": 'fct_b["fct_b · 2"]' in page
        and "raw__a --> stg_a" in page
        and "seeds --> fct_b" in page
        and seeds == 1,
        "planted: a moved test changes the page (the check would see it)": render(planted) != page
        and 'stg_a["stg_a · 1"]' in render(planted),
        "deterministic": render(manifest) == page,
    }
    for name, ok in checks.items():
        print(f"{'✅' if ok else '🔴'} {name}")
    return 0 if all(checks.values()) else 1


def main() -> int:
    utf8_stdio()
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--manifest", type=Path, default=MANIFEST)
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument("--check", action="store_true", help="exit 1 if the page is out of date")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        return self_test()
    try:
        page = render(json.loads(args.manifest.read_text("utf-8")))
    except (OSError, ValueError, KeyError) as exc:
        print(f"🔴 cannot read the manifest {args.manifest}: {type(exc).__name__}: {exc}")
        return 2
    if args.check:
        current = args.out.read_text("utf-8") if args.out.exists() else ""
        if current != page:
            print(f"🔴 {args.out.name} is out of date: run python tools/lineage_mermaid.py")
            return 1
        print(f"✅ {args.out.name} matches the models")
        return 0
    args.out.write_text(page, "utf-8", newline="\n")
    print(f"✅ written {args.out.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
